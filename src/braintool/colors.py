"""Пастельная палитра: один устойчивый цвет на животное (по индексу-столбцу)."""
from __future__ import annotations

# RGB, насыщенные пастельные тона ("candy" pastel) — мягкие, но с заметно большей
# насыщенностью, чем классический бледный пастель. Первая, более светлая версия
# палитры оказалась плохо видна поверх тёмного фото (пользователь: "маски поярче,
# не видно"), поэтому цвета сделаны более яркими при сохранении пастельного характера.
PASTEL_PALETTE: list[tuple[int, int, int]] = [
    (255, 99, 132),   # яркий розово-коралловый
    (64, 156, 255),   # яркий голубой
    (72, 214, 130),   # яркий мятно-зелёный
    (255, 170, 60),   # яркий персиково-оранжевый
    (177, 97, 255),   # яркий лавандовый
    (255, 219, 64),   # яркий жёлтый
    (64, 224, 208),   # яркий бирюзовый
    (255, 105, 180),  # яркая фуксия
    (154, 230, 80),   # яркий салатовый
    (120, 130, 255),  # яркий сиренево-синий
]


def color_for_animal(animal_index: int) -> tuple[int, int, int]:
    """Возвращает RGB-цвет для животного с данным индексом (0-based).

    Цвета переиспользуются по кругу, если животных больше, чем цветов в палитре.
    """
    return PASTEL_PALETTE[animal_index % len(PASTEL_PALETTE)]
